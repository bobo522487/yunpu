import { createHash, timingSafeEqual } from "node:crypto";
import { type Context, Hono } from "hono";
import { config } from "./config";
import { getObject, putObject } from "./storage";

const media = new Hono();

// 1 MB body limit. It serves this feature's proof only, not product media rules.
const maxBodyBytes = 1024 * 1024;

// randomKey() produces media/<8-digit date>T<4-digit time>/<32 hex>.
export const MEDIA_KEY_PATTERN = /^media\/[0-9]{8}T[0-9]{4}\/[0-9a-f]{32}$/;

export function isAllowedMediaKey(key: string): boolean {
  return MEDIA_KEY_PATTERN.test(key);
}

function sha256(value: string): Buffer {
  return createHash("sha256").update(value, "utf8").digest();
}

function authorized(request: Request): boolean {
  const expected = config().YUNPU_CAPABILITY_TOKEN;
  if (!expected) {
    return false;
  }
  const header = request.headers.get("authorization");
  if (!header?.startsWith("Bearer ")) {
    return false;
  }
  const token = header.slice("Bearer ".length);
  return timingSafeEqual(sha256(token), sha256(expected));
}

function unauthorized(c: Context) {
  return c.json(
    { ok: false, reason: "missing or invalid capability token" },
    401,
  );
}

function randomKey(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  const hex = [...bytes].map((b) => b.toString(16).padStart(2, "0")).join("");
  const now = new Date().toISOString().replace(/[-:]/g, "").slice(0, 13);
  return `media/${now}/${hex}`;
}

media.post("/api/media", async (c) => {
  if (!authorized(c.req.raw)) {
    return unauthorized(c);
  }

  const declaredLength = Number(c.req.header("content-length") ?? 0);
  if (Number.isFinite(declaredLength) && declaredLength > maxBodyBytes) {
    return c.json({ ok: false, reason: "body exceeds 1 MB limit" }, 413);
  }

  // A declared length is a hint, not a bound: chunked bodies and lying clients
  // must not be able to make us buffer an unbounded stream. Count bytes as they
  // arrive and cancel the reader as soon as the cap is crossed.
  const stream = c.req.raw.body;
  if (!stream) {
    return c.json({ ok: false, reason: "request body is required" }, 400);
  }
  const reader = stream.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  let exceeded = false;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      total += value.byteLength;
      if (total > maxBodyBytes) {
        exceeded = true;
        await reader.cancel();
        break;
      }
      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }
  if (exceeded) {
    return c.json({ ok: false, reason: "body exceeds 1 MB limit" }, 413);
  }

  const body = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    body.set(chunk, offset);
    offset += chunk.byteLength;
  }

  // The key is generated by the application; the caller cannot choose it.
  const key = randomKey();
  await putObject(key, body);

  return c.json({ ok: true, key }, 201);
});

// Keys contain slashes (media/<stamp>/<hex>), so the read route must match
// the rest of the path, not a single segment.
media.get("/api/media/*", async (c) => {
  if (!authorized(c.req.raw)) {
    return unauthorized(c);
  }

  const prefix = "/api/media/";
  const path = c.req.path;
  if (!path.startsWith(prefix) || path.length <= prefix.length) {
    return c.json({ ok: false, reason: "object not found" }, 404);
  }
  const key = path.slice(prefix.length);
  if (!isAllowedMediaKey(key)) {
    return c.json({ ok: false, reason: "invalid object key" }, 400);
  }
  const data = await getObject(key);
  if (!data) {
    return c.json({ ok: false, reason: "object not found" }, 404);
  }

  return new Response(new Uint8Array(data), {
    status: 200,
    headers: { "content-type": "application/octet-stream" },
  });
});

export default media;

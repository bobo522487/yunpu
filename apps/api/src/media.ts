import { Hono, type Context } from "hono";
import { getObject, putObject } from "./storage";

const media = new Hono();

// 1 MB body limit. It serves this feature's proof only, not product media rules.
const maxBodyBytes = 1024 * 1024;

function authorized(request: Request): boolean {
  const expected = process.env.YUNPU_CAPABILITY_TOKEN;
  if (!expected) {
    return false;
  }
  const header = request.headers.get("authorization");
  if (!header?.startsWith("Bearer ")) {
    return false;
  }
  const token = header.slice("Bearer ".length);
  // Constant-time-ish comparison; both environments' tokens are single strings.
  if (token.length !== expected.length) {
    return false;
  }
  let diff = 0;
  for (let i = 0; i < expected.length; i += 1) {
    diff |= token.charCodeAt(i) ^ expected.charCodeAt(i);
  }
  return diff === 0;
}

function unauthorized(c: Context) {
  return c.json({ ok: false, reason: "missing or invalid capability token" }, 401);
}

function randomKey(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  const hex = [...bytes].map((b) => b.toString(16).padStart(2, "0")).join("");
  const now = new Date().toISOString().replace(/[-:]/g, "").slice(0, 13);
  return `media/${now}/${hex}`;
}

media.post("/api/media", async (c) => {
  if (!authorized(c.req.raw)) {
    return unauthorized(c);
  }

  const body = await c.req.arrayBuffer();
  if (body.byteLength > maxBodyBytes) {
    return c.json({ ok: false, reason: "body exceeds 1 MB limit" }, 413);
  }

  // The key is generated by the application; the caller cannot choose it.
  const key = randomKey();
  await putObject(key, new Uint8Array(body));

  return c.json({ ok: true, key }, 201);
});

media.get("/api/media/:key", async (c) => {
  if (!authorized(c.req.raw)) {
    return unauthorized(c);
  }

  const key = c.req.param("key");
  const data = await getObject(key);
  if (!data) {
    return c.json({ ok: false, reason: "object not found" }, 404);
  }

  return new Response(data, {
    status: 200,
    headers: { "content-type": "application/octet-stream" },
  });
});

export default media;

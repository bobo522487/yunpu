export const DEFAULT_REGION_PATH = '中国/北京/东城';

export function parseRegionParts(value?: string): string[] {
  if (!value || !value.trim()) return ['中国', '北京', '东城'];
  return value
    .split('/')
    .map((s) => s.trim())
    .filter(Boolean);
}

export function formatRegionParts(parts: string[]): string {
  return parts.filter(Boolean).join('/');
}

export function findEraById(eraId?: string): EraDefinition | undefined {
  if (!eraId) return undefined;
  return REIGN_ERAS.find((e) => e.id === eraId);
}

export function findEraByName(eraName?: string): EraDefinition | undefined {
  if (!eraName) return undefined;
  const trimmed = eraName.trim();
  return REIGN_ERAS.find(
    (e) => e.eraName === trimmed || `${e.dynastyName}${e.eraName}` === trimmed
  );
}

export function formatHistoricalYearSpan(era: EraDefinition): string {
  const fmt = (y: number) => (y < 0 ? `前${Math.abs(y)}年` : `${y}年`);
  return `${fmt(era.startYear)} – ${fmt(era.endYear)}`;
}

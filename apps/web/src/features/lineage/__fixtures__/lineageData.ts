export function createSeedPersonsForChart(
  chartId: string,
  chartName?: string,
  surname?: string,
  progenitor?: string
): PersonRecord[] {
  if (chartId === 'lineage-royal-1') {
    return structuredClone(HAN_ROYAL_PERSONS);
  }

  if (
    chartId.startsWith('lineage-royal-') ||
    chartId.startsWith('lineage-other-') ||
    chartId.startsWith('lineage-ancestor-')
  ) {
    const cloned = structuredClone(INITIAL_PERSONS);
    return cloned.map((p, idx) => ({
      ...p,
      id: `${chartId}-${p.id}`,
      fatherId: p.fatherId ? `${chartId}-${p.fatherId}` : null,
      motherId: p.motherId ? `${chartId}-${p.motherId}` : undefined,
      spouseOfId: p.spouseOfId ? `${chartId}-${p.spouseOfId}` : undefined,
      branchId: chartId,
      sequenceMeta: {
        ...(p.sequenceMeta || {}),
        originalPage: p.sequenceMeta?.originalPage ?? 20 + idx * 2,
      },
      biographyOrder: p.biographyOrder ?? idx + 1,
    }));
  }

  return createStarterProgenitorForChart(
    chartId,
    chartName,
    surname,
    progenitor,
  );
}

export function createDemoLineagePayload(projectId: string): {
  tree: TreeItem[];
  personsByChart: Record<string, PersonRecord[]>;
  selectedNodeId: string;
} {
  const tree = structuredClone(ROYAL_DEMO_LINEAGE_TREE);
  const charts = collectTreeNodesByType(tree, 'chart');
  const personsByChart: Record<string, PersonRecord[]> = {};
  for (const chart of charts) {
    const chartId = String(chart.id);
    personsByChart[`${projectId}::${chartId}`] = createSeedPersonsForChart(
      chartId,
      chart.data?.name,
      chart.data?.surname,
    );
  }
  const selectedNodeId = charts[0]
    ? String(charts[0].id)
    : String(tree[0]?.id ?? '');
  return { tree, personsByChart, selectedNodeId };
}
